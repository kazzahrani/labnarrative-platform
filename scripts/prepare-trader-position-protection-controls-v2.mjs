import fs from "node:fs";
import path from "node:path";
await import("./prepare-trader-position-protection-controls-v1.mjs");
const file=path.join(process.cwd(),"app/trader/TradeActionsV2.tsx");
let source=fs.readFileSync(file,"utf8");
source=source.replaceAll("\\`","`").replaceAll("\\${","${");
source=source.replace('accountMode: "paper" | "live";','accountMode: "paper" | "shadow" | "live";');
source=source.replace('  onRefresh: () => Promise<void> | void;','  onRefresh?: () => Promise<void> | void;\n  onChanged?: () => Promise<void> | void;');
source=source.replace('  const {trade,onRefresh}=props;','  const {trade}=props;\n  const refresh=props.onChanged ?? props.onRefresh ?? (() => undefined);');
source=source.replace('void Promise.resolve(onRefresh()).catch(()=>undefined);','void Promise.resolve(refresh()).catch(()=>undefined);');
fs.writeFileSync(file,source);
console.log("Normalized generated SL/TP action templates and V1 callback contract.");
